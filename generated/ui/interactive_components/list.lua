---Creates a new list on the specified parent.
---@param parent ui.ComponentCollection Parent component to create this list in.
---@param categoryID Int? Category ID used to identify this component. Defaults to the parent's category ID if not specified.
---@param dynamicID Int? Dynamic ID used to identify this component. Defaults to auto-incrementing from the parent's dynamic ID if not specified.
---@return List # The newly created list. The caller must set its layout and visual information afterwards.
function ui.List.new(parent, categoryID, dynamicID) end

---Adds an entry to this list with the provided label and ID.
---@param label String The text to display for this entry.
---@param id Int Unique value used to identify this entry.
---@return Bool # True if the entry was added successfully, false otherwise. This function can fail and return false due to the provided ID already existing.
function ui.List:Add(label, id) end

---Clears existing entries from the list and adds all entries in the provided container to the list, optionally selecting the one with the provided ID.
---@overload fun(self: ui.List, entriesMap: table<String, Int>, selectedID: Int?): Bool
---@param entries String[] Array of entry names to add to this list. Their respective IDs are autogenerated using an auto-incrementing integer.
---@param selectedID Int? ID for the entry to be selected afterwards. If this is an invalid ID or not specified, the first entry will be selected instead for lists that always require at least one selected entry (dropdowns for example).
---@return Bool # True if the provided entries were valid and were successfully added to the list, false otherwise. This function can fail and return false due to the provided ID already existing, or due to invalid/malformed data.
function ui.List:SetEntries(entries, selectedID) end

---Removes all entries from this list.
function ui.List:Clear() end

---Deselects all currently selected entries in a multiple selection list (defined via the maxSelected property). Does nothing for single selection lists.
function ui.List:UnselectAll() end

---Sets whether or not the entry associated with the provided ID is enabled and can be selected.
---@param id Int Numeric value associated with the entry to modify.
---@param enabled Bool Whether or not the entry should be enabled and selectable.
---@return Bool # True if there was an entry corresponding to the provided ID, false otherwise.
function ui.List:SetEntryEnabled(id, enabled) end

---Sets whether or not the entry associated with the provided ID is visible to the user.
---@param id Int Numeric value associated with the entry to modify.
---@param visible Bool Whether or not the entry should be enabled visible to the user.
---@return Bool # True if there was an entry corresponding to the provided ID, false otherwise.
function ui.List:SetEntryVisible(id, visible) end

---Sets whether or not the entry associated with the provided ID is selected, and optionally triggers the corresponding ONSELECTIONCHANGED events.
---@param id Int Numeric value associated with the entry to modify.
---@param selected Bool Whether or not the entry should be selected.
---@param triggerEvents Bool? Whether or not to emit ONSELECTIONCHANGED events for this change. Defaults to false.
---@return Bool # True if there was an entry corresponding to the provided ID, false otherwise.
function ui.List:SetEntrySelected(id, selected, triggerEvents) end

---Sets the icon for the entry associated with the provided ID.
---@param id Int Numeric value associated with the entry to modify.
---@param spriteID Int Numeric ID associated with the sprite to use as an icon for this entry.
---@return Bool # True if there was an entry corresponding to the provided ID, false otherwise.
function ui.List:SetEntryIcon(id, spriteID) end

---Returns whether or not the entry associated with the provided ID is enabled and selectable.
---@param id Int Numeric value associated with the entry to access.
---@return Bool # True if there was an entry corresponding to the provided ID and it was enabled, false otherwise.
function ui.List:GetEntryEnabled(id) end

---Returns whether or not the entry associated with the provided ID is visible to the user.
---@param id Int Numeric value associated with the entry to access.
---@return Bool # True if there was an entry corresponding to the provided ID and it was visible, false otherwise.
function ui.List:GetEntryVisible(id) end

---Returns whether or not the entry associated with the provided ID is selected.
---@param id Int Numeric value associated with the entry to access.
---@return Bool # True if there was an entry corresponding to the provided ID and it was selected, false otherwise.
function ui.List:GetEntrySelected(id) end

---Returns whether or not there's an entry associated with the provided ID.
---@param id Int Numeric value associated with the entry to check.
---@return Bool # True if there is an entry corresponding to the provided ID, false otherwise.
function ui.List:HasEntry(id) end

